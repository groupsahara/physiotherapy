import { joinParts } from "@/lib/contact-links";
import type { Site } from "@/lib/cms/types";

export const OG_IMAGE_SIZE = { width: 1200, height: 630 };
export const OG_IMAGE_TYPE = "image/png";

export interface ShareImage {
  /** Site-relative or absolute URL. */
  url: string;
  alt: string;
  width?: number;
  height?: number;
  type?: string;
}

/** e.g. "Clinic Legal Name — Locality, City". */
export function shareImageAlt(site: Site): string {
  const { "site.identity": identity, "site.contact": contact } = site.documents;
  return joinParts(
    [identity.legalName || identity.name, joinParts([contact.address.locality, contact.address.city], ", ")],
    " — ",
  );
}

/**
 * The share image chosen in the CMS when set, otherwise the card generated by
 * `app/opengraph-image.tsx`. The content version in the query makes social networks
 * fetch the card again after a content change.
 */
export function shareImageFor(site: Site): ShareImage {
  const { shareImage } = site.documents["site.seo"];
  const alt = shareImageAlt(site);
  if (shareImage) return { url: shareImage.src, alt: shareImage.alt || alt };

  const version = site.version ? `?v=${encodeURIComponent(site.version)}` : "";
  return { url: `/opengraph-image${version}`, alt, ...OG_IMAGE_SIZE, type: OG_IMAGE_TYPE };
}
